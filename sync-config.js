/*
 * 单一配置源同步器。
 *
 *   node sync-config.js
 *
 * 1) 校验 game-config.json 的完整性；
 * 2) 生成 Config.cs（C# 版只读这一份生成物，不手写常量）；
 * 3) 把同一份 JSON 注入 index.html 的 CFG 块，网页版仍是单文件；
 * 4) 核对两版的逻辑函数是否一一对应，避免"改了一个版本忘了另一个"。
 *
 * 改玩法参数只改 game-config.json，然后跑一次本脚本。
 */
'use strict';
const fs = require('fs');
const path = require('path');

const dir = __dirname;
const read = f => fs.readFileSync(path.join(dir, f), 'utf8');
const write = (f, s) => fs.writeFileSync(path.join(dir, f), s, 'utf8');
const cfg = JSON.parse(read('game-config.json'));

// ---------- 1. 配置校验 ----------
const errors = [];
if (cfg.board.lanes.length < 2) errors.push('至少需要两条车道');
if (cfg.rules.startLives < 1 || cfg.rules.startLives > cfg.rules.maxLives) errors.push('startLives 非法');
if (cfg.rules.fixedStep <= 0) errors.push('fixedStep 必须为正');
if (cfg.difficulty.spawnMin <= 0) errors.push('spawnMin 必须为正');
for (const name of Object.keys(cfg.patterns)) {
  for (const w of cfg.patterns[name].waves) {
    if (w.block.length >= cfg.board.lanes.length) errors.push(name + ' 存在堵死全部车道的波次');
    for (const li of w.block) if (li < 0 || li >= cfg.board.lanes.length) errors.push(name + ' 车道索引越界: ' + li);
    if (w.coin !== undefined && (w.coin < 0 || w.coin >= cfg.board.lanes.length)) errors.push(name + ' 金币车道越界');
  }
}
for (const pool of cfg.difficulty.wavePools)
  for (const p of pool.patterns)
    if (!cfg.patterns[p]) errors.push('波次池引用了不存在的图案: ' + p);
if (errors.length) {
  console.error('配置校验失败:\n  - ' + errors.join('\n  - '));
  process.exit(1);
}

// ---------- 2. 生成 Config.cs ----------
const pascal = s => s.charAt(0).toUpperCase() + s.slice(1);
const intArr = a => 'new int[] { ' + a.join(', ') + ' }';
const strArr = a => 'new string[] { ' + a.map(x => JSON.stringify(x)).join(', ') + ' }';
const ctype = v => (Number.isInteger(v) ? 'int' : 'double');
const cval = v => (Number.isInteger(v) ? String(v) : String(v) + 'D');

const L = [];
L.push('// <auto-generated>');
L.push('// 由 game-config.json 生成，请勿手改；运行 node sync-config.js 重新生成。');
L.push('// </auto-generated>');
L.push('using System.Collections.Generic;');
L.push('');
L.push('namespace PixelRacer');
L.push('{');
L.push('    internal sealed class WaveDef');
L.push('    {');
L.push('        public int[] Block;');
L.push('        public int Coin;');
L.push('        public WaveDef(int[] block, int coin) { Block = block; Coin = coin; }');
L.push('    }');
L.push('    internal sealed class Pattern');
L.push('    {');
L.push('        public bool Sequence;');
L.push('        public WaveDef[] Waves;');
L.push('        public Pattern(bool sequence, WaveDef[] waves) { Sequence = sequence; Waves = waves; }');
L.push('    }');
L.push('    internal sealed class Pool');
L.push('    {');
L.push('        public int UpToStage;');
L.push('        public string[] Patterns;');
L.push('        public Pool(int upToStage, string[] patterns) { UpToStage = upToStage; Patterns = patterns; }');
L.push('    }');
L.push('');
L.push('    internal static class Config');
L.push('    {');
L.push('        public const int Version = ' + cfg.version + ';');
L.push('');
L.push('        // 棋盘');
for (const [k, v] of Object.entries(cfg.board)) {
  if (Array.isArray(v)) L.push('        public static readonly int[] ' + pascal(k) + ' = ' + intArr(v) + ';');
  else L.push('        public const ' + ctype(v) + ' ' + pascal(k) + ' = ' + cval(v) + ';');
}
L.push('');
L.push('        // 配色');
for (const [k, v] of Object.entries(cfg.colors))
  L.push('        public const string ' + pascal(k) + ' = ' + JSON.stringify(v) + ';');
L.push('        public static readonly string[] EnemyColors = ' + strArr(cfg.enemyColors) + ';');
L.push('');
L.push('        // 规则');
for (const [k, v] of Object.entries(cfg.rules))
  L.push('        public const ' + ctype(v) + ' ' + pascal(k) + ' = ' + cval(v) + ';');
L.push('');
L.push('        // 难度');
for (const [k, v] of Object.entries(cfg.difficulty)) {
  if (k === 'wavePools' || k === 'patterns') continue;
  L.push('        public const ' + ctype(v) + ' ' + pascal(k) + ' = ' + cval(v) + ';');
}
L.push('        public static readonly Pool[] WavePools = new Pool[]');
L.push('        {');
for (const p of cfg.difficulty.wavePools)
  L.push('            new Pool(' + p.upToStage + ', ' + strArr(p.patterns) + '),');
L.push('        };');
L.push('        public static readonly Dictionary<string, Pattern> Patterns = new Dictionary<string, Pattern>');
L.push('        {');
for (const [name, p] of Object.entries(cfg.patterns)) {
  const waves = p.waves.map(w =>
    'new WaveDef(' + intArr(w.block) + ', ' + (w.coin === undefined ? -1 : w.coin) + ')').join(', ');
  L.push('            { ' + JSON.stringify(name) + ', new Pattern(' + (p.sequence ? 'true' : 'false') +
         ', new WaveDef[] { ' + waves + ' }) },');
}
L.push('        };');
L.push('    }');
L.push('}');
L.push('');
write('Config.cs', L.join('\n'));
console.log('Config.cs          <- game-config.json  (' + L.length + ' 行)');

// ---------- 2b. 生成 game-config.h（纯 C 版） ----------
// 颜色写成 0xRRGGBB：小端 32bpp DIB 的内存布局正好是 B,G,R,0，无需逐通道转换。
const macro = s => 'GC_' + s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase();
const hex = c => c.replace('#', '0x') + 'UL';
const CH = [];
CH.push('/* <auto-generated>');
CH.push('   Generated from game-config.json. DO NOT EDIT.');
CH.push('   Run node sync-config.js to regenerate. Shared by the C, C# and web builds.');
CH.push('   Kept ASCII-only: MSVC may read C sources using the local code page.');
CH.push('</auto-generated> */');
CH.push('#ifndef PIXEL_RACER_CONFIG_H');
CH.push('#define PIXEL_RACER_CONFIG_H');
CH.push('');
CH.push('#define GC_VERSION ' + cfg.version);
CH.push('');
CH.push('/* board */');
for (const [k, v] of Object.entries(cfg.board)) {
  if (Array.isArray(v)) {
    CH.push('#define GC_LANE_COUNT ' + v.length);
    CH.push('static const int ' + macro(k) + '[] = { ' + v.join(', ') + ' };');
  } else CH.push('#define ' + macro(k) + ' ' + v);
}
CH.push('');
CH.push('/* colors: 0xRRGGBB; little-endian 32bpp DIB memory is B,G,R,0 */');
for (const [k, v] of Object.entries(cfg.colors)) CH.push('#define ' + macro(k) + ' ' + hex(v));
CH.push('#define GC_ENEMY_COLOR_COUNT ' + cfg.enemyColors.length);
CH.push('static const unsigned int GC_ENEMY_COLORS[GC_ENEMY_COLOR_COUNT] = { ' +
        cfg.enemyColors.map(hex).join(', ') + ' };');
CH.push('');
CH.push('/* rules */');
for (const [k, v] of Object.entries(cfg.rules)) CH.push('#define ' + macro(k) + ' ' + v);
CH.push('');
CH.push('/* difficulty */');
for (const [k, v] of Object.entries(cfg.difficulty)) {
  if (k === 'wavePools' || k === 'patterns') continue;
  CH.push('#define ' + macro(k) + ' ' + v);
}
const names = Object.keys(cfg.patterns);
const maxWaves = Math.max.apply(null, names.map(n => cfg.patterns[n].waves.length));
const maxPats = Math.max.apply(null, cfg.difficulty.wavePools.map(p => p.patterns.length));
CH.push('');
CH.push('/* wave patterns */');
CH.push('typedef struct { int n; int block[GC_LANE_COUNT]; int coin; } GCW;');
CH.push('typedef struct { int sequence; int nw; GCW w[' + maxWaves + ']; } GCP;');
CH.push('typedef struct { int upTo; int n; int pats[' + maxPats + ']; } GCPOOL;');
CH.push('enum {');
names.forEach((n, i) => CH.push('  GC_P_' + n.toUpperCase() + ' = ' + i + ','));
CH.push('  GC_P_COUNT');
CH.push('};');
CH.push('static const GCP GC_PATTERNS[GC_P_COUNT] = {');
for (const n of names) {
  const p = cfg.patterns[n];
  const waves = p.waves.map(w => {
    const b = [];
    for (let i = 0; i < cfg.board.lanes.length; i++)
      b.push(i < w.block.length ? w.block[i] : 0);
    return '{ ' + w.block.length + ', { ' + b.join(', ') + ' }, ' +
           (w.coin === undefined ? -1 : w.coin) + ' }';
  });
  while (waves.length < maxWaves) waves.push('{ 0, { 0 }, -1 }');
  CH.push('  /* ' + n + ' */ { ' + (p.sequence ? 1 : 0) + ', ' + p.waves.length +
          ', { ' + waves.join(', ') + ' } },');
}
CH.push('};');
CH.push('#define GC_POOL_COUNT ' + cfg.difficulty.wavePools.length);
CH.push('static const GCPOOL GC_POOLS[GC_POOL_COUNT] = {');
for (const pool of cfg.difficulty.wavePools) {
  const pats = pool.patterns.map(n => 'GC_P_' + n.toUpperCase());
  while (pats.length < maxPats) pats.push('0');
  CH.push('  { ' + pool.upToStage + ', ' + pool.patterns.length +
          ', { ' + pats.join(', ') + ' } },');
}
CH.push('};');
CH.push('');
CH.push('#endif /* PIXEL_RACER_CONFIG_H */');
CH.push('');
write('game-config.h', CH.join('\n'));
console.log('game-config.h      <- game-config.json  (' + CH.length + ' 行)');

// ---------- 3. 注入 index.html ----------
const html = read('index.html');
const marker = /\/\/ <<< CONFIG:BEGIN >>>[\s\S]*?\/\/ <<< CONFIG:END >>>/;
if (!marker.test(html)) {
  console.error('index.html 缺少 CONFIG:BEGIN / CONFIG:END 标记，无法注入。');
  process.exit(1);
}
const json = JSON.stringify(cfg, null, 2).split('\n').join('\n  ');
const block = '// <<< CONFIG:BEGIN >>>\n' +
  '  // 由 game-config.json 自动生成；改参数请改 JSON 后运行 node sync-config.js\n' +
  '  const CFG = ' + json + ';\n' +
  '  // <<< CONFIG:END >>>';
write('index.html', html.replace(marker, block));
console.log('index.html CFG 块  <- game-config.json  (' + JSON.stringify(cfg).length + ' 字节)');

// ---------- 4. 三版本逻辑函数对齐 ----------
const shared = [
  'reset', 'start', 'gameOver', 'panel', 'drawTitle', 'drawPause', 'drawOver',
  'makeEnemy', 'spawnCoin', 'burst', 'update', 'render',
  'drawCar', 'drawRoad', 'drawCoin', 'drawHUD', 'drawWarn', 'drawFloaters',
  'drawSceneryFar', 'drawSceneryNear', 'drawSpeedLines',
  'queueWave', 'emitWave', 'ensureReachable', 'waveInterval',
  'addFloater', 'hitEnemy'
];
const htmlFns = new Set();
let m;
const reHtml = /function\s+([A-Za-z_$][\w$]*)\s*\(/g;
while ((m = reHtml.exec(read('index.html')))) htmlFns.add(m[1]);
const csFns = new Set();
const reCs = /\b(?:void|double|int|bool|string|Bitmap|Enemy|float)\s+([A-Z]\w*)\s*\(/g;
while ((m = reCs.exec(read('Program.cs')))) csFns.add(m[1]);
const hasC = fs.existsSync(path.join(dir, 'main.c'));
const cFns = new Set();
if (hasC) {
  const reC = /\b(?:void|int|double|Enemy|Wave|float)\s+([a-z]\w*)\s*\(/g;
  while ((m = reC.exec(read('main.c')))) cFns.add(m[1]);
}

const missing = [];
for (const fn of shared) {
  if (!htmlFns.has(fn)) missing.push('index.html 缺少 ' + fn + '()');
  if (!csFns.has(pascal(fn))) missing.push('Program.cs 缺少 ' + pascal(fn) + '()');
  if (hasC && !cFns.has(fn)) missing.push('main.c 缺少 ' + fn + '()');
}
if (missing.length) {
  console.error('函数对齐失败:\n  - ' + missing.join('\n  - '));
  process.exit(1);
}
console.log((hasC ? '三版本' : '双版本') + '函数对齐     OK (' +
            shared.length + ' 个逻辑函数一一对应)');
console.log('同步完成。');
